"""Foreground single-operator SSH road; this tool neither installs VPN nor retrieves credentials."""

import argparse
import json
import os
import shutil
import socket
import subprocess

import client


def command(peer, identity, known_hosts):
    address = client.address(peer)
    paths = [client.private_file(value) for value in (identity, known_hosts)]
    if any(character in path for path in paths for character in "\r\n%"):
        raise ValueError("Private paths cannot contain SSH expansion tokens or line breaks")
    quoted_hosts = '"' + paths[1].replace("\\", "\\\\").replace('"', '\\"') + '"'
    return [
        "ssh",
        "-F",
        "/dev/null",
        "-N",
        "-T",
        "-p",
        "2222",
        "-i",
        paths[0],
        "-o",
        "IdentitiesOnly=yes",
        "-o",
        "IdentityAgent=none",
        "-o",
        "BatchMode=no",
        "-o",
        "StrictHostKeyChecking=yes",
        "-o",
        f"UserKnownHostsFile={quoted_hosts}",
        "-o",
        "GlobalKnownHostsFile=/dev/null",
        "-o",
        "UpdateHostKeys=no",
        "-o",
        "VerifyHostKeyDNS=no",
        "-o",
        "PreferredAuthentications=publickey",
        "-o",
        "PasswordAuthentication=no",
        "-o",
        "KbdInteractiveAuthentication=no",
        "-o",
        "ConnectTimeout=10",
        "-o",
        "ConnectionAttempts=1",
        "-o",
        "ExitOnForwardFailure=yes",
        "-o",
        "ForwardAgent=no",
        "-o",
        "ServerAliveInterval=15",
        "-o",
        "ServerAliveCountMax=2",
        "-o",
        "ControlMaster=no",
        "-o",
        "ControlPath=none",
        "-L",
        "127.0.0.1:7134:127.0.0.1:7134",
        f"lychd-forward@{address}",
    ]


def wireguard_route(peer, interface):
    """Refuse a missing/down tunnel and any LAN/default-route fallback before SSH starts."""
    peer = client.address(peer)
    interface = client.interface(interface)
    ip = shutil.which("ip", path="/usr/sbin:/usr/bin:/sbin:/bin")
    if not ip:
        raise ValueError("Install iproute2 before opening the private road")

    def observe(arguments):
        result = subprocess.run([ip, *arguments], capture_output=True, text=True, timeout=10, check=False)
        if result.returncode:
            raise ValueError("WireGuard route unavailable; no alternate route will be used")
        return json.loads(result.stdout)

    links = observe(["-d", "-j", "link", "show", "dev", interface])
    if (
        len(links) != 1
        or links[0].get("linkinfo", {}).get("info_kind") != "wireguard"
        or "UP" not in links[0].get("flags", [])
    ):
        raise ValueError("The selected interface must be an up WireGuard device")
    routes = observe(["-j", "route", "get", peer])
    if len(routes) != 1 or routes[0].get("dev") != interface or routes[0].get("type", "unicast") != "unicast":
        raise ValueError("The VPS address does not route through the selected WireGuard interface")
    return {"peer": peer, "interface": interface}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", help="Private connection.json generated by client.py")
    parser.add_argument("--peer")
    parser.add_argument("--identity")
    parser.add_argument("--known-hosts")
    parser.add_argument("--interface")
    parser.add_argument(
        "--check", action="store_true", help="Observe files, route and free local port without starting SSH"
    )
    args = parser.parse_args()
    try:
        if args.profile:
            if any((args.peer, args.identity, args.known_hosts, args.interface)):
                raise ValueError("Use one connection profile or the four explicit connection options")
            profile = client.load_connection(args.profile)
            args.peer, args.identity, args.known_hosts, args.interface = (
                profile[name] for name in ("server_address", "ssh_identity", "known_hosts", "interface")
            )
        elif not all((args.peer, args.identity, args.known_hosts, args.interface)):
            raise ValueError("Supply --profile, or --peer, --identity, --known-hosts and --interface")
        argv = command(args.peer, args.identity, args.known_hosts)
        observation = wireguard_route(args.peer, args.interface)
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
            listener.bind(("127.0.0.1", 7134))
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError) as error:
        parser.error(str(error))
    if args.check:
        print(json.dumps({**observation, "state": "local_preflight_passed", "ssh_and_browser": "not tested"}))
        return
    # SSH performs the authoritative bind after this diagnostic probe; ExitOnForwardFailure
    # closes a race with another process. No browser is opened and no credential is read.
    os.execvp(argv[0], argv)


if __name__ == "__main__":
    main()
