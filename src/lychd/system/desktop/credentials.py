"""Private per-user credential files for native desktop installation."""

from __future__ import annotations

import os
import re
import secrets
from pathlib import Path

import click

from lychd.system.constants import PATH_POSTGRES_ROOT_DIR
from lychd.system.desktop.private import (
    check_path,
    overlaps,
    private_directory,
    private_file,
    publish_file,
    verify_private_directory,
    verify_private_file,
)

_RUNTIME = ("LYCHD_RUNTIME_DB_PASSWORD", "LYCHD_APP_SECRET_KEY", "LYCHD_LOCAL_ACCESS_PASSWORD")
_ADMIN = ("LYCHD_DB_PASSWORD", "LYCHD_PHOENIX_DB_PASSWORD")
GENERATED = (*_RUNTIME, *_ADMIN)


def load_credentials(
    *, administrative: bool = False, provision: bool = False, required: bool = False, allow_rotation: bool = False
) -> None:
    """Set standard file references without replacing explicit credentials or disclosing values."""
    directory = PATH_POSTGRES_ROOT_DIR / "desktop-credentials"
    if not allow_rotation and (directory / "pending-runtime-rotation.json").exists():
        msg = "A runtime credential rotation is pending. Repeat desktop rotate-runtime-password with the original recovery directory."
        raise click.ClickException(msg)
    if provision:
        private_directory(directory)
    for name in GENERATED if administrative else _RUNTIME:
        file_key = f"{name}_FILE"
        if os.environ.get(name) or os.environ.get(file_key):
            continue
        path = directory / name.lower()
        check_path(path)
        if provision and not path.exists():
            publish_file(path, secrets.token_urlsafe(48).encode("ascii"))
        if required and not path.is_file():
            msg = f"Missing desktop credential {name}. Restore its original file or supply its explicit override."
            raise click.ClickException(msg)
        if path.is_file():
            private_file(path)
            os.environ[file_key] = str(path)


def verify_recovery_directory(directory: Path) -> None:
    """Verify private recovery storage outside the database, credentials and selected volume."""
    from lychd.system.desktop.volume_storage import authority, selected

    verify_private_directory(directory)
    default = PATH_POSTGRES_ROOT_DIR / "native-data"
    if overlaps(directory, PATH_POSTGRES_ROOT_DIR) or (
        authority(default).exists() and overlaps(directory, selected(default)[0])
    ):
        msg = "Select a private recovery directory outside the active desktop database and credential storage."
        raise ValueError(msg)


def verify_credential_copy(directory: Path) -> None:
    """Compare an independent, private copy of every generated credential to this installation."""
    source = PATH_POSTGRES_ROOT_DIR / "desktop-credentials"
    verify_private_directory(source)
    verify_recovery_directory(directory)
    for name in GENERATED:
        original = source / name.lower()
        reference = os.environ.get(f"{name}_FILE")
        if os.environ.get(name) or (reference and Path(reference) != original):
            msg = f"{name} has an explicit override. Verify it through the external credential owner."
            raise click.ClickException(msg)
        copy = directory / name.lower()
        verify_private_file(copy)
        value = generated_value(original, name)
        if not value or not secrets.compare_digest(value, copy.read_bytes()):
            msg = f"Credential backup does not match {name}."
            raise click.ClickException(msg)
        recovery_value(copy)


def resolve_vault_reference(name: str, path: Path, record: str) -> str:
    """Allow OS vault references only at the exact generated path for the requested secret."""
    from lychd.system.desktop.vault import open_credential

    if name not in GENERATED or path != PATH_POSTGRES_ROOT_DIR / "desktop-credentials" / name.lower():
        msg = "Desktop vault references are restricted to the matching generated credential file."
        raise ValueError(msg)
    verify_private_file(path)
    return open_credential(path, record)


def generated_value(path: Path, name: str) -> bytes:
    from lychd.system.desktop.vault import PREFIX

    verify_private_file(path)
    value = path.read_bytes()
    if value.startswith(PREFIX.encode()):
        return resolve_vault_reference(name, path, value.decode("ascii")).encode("ascii")
    return value


def recovery_value(path: Path) -> bytes:
    """Recovery media contain the portable original generated by token_urlsafe(48)."""
    verify_private_file(path)
    value = path.read_bytes()
    if not re.fullmatch(rb"[a-zA-Z0-9_-]{64}", value):
        msg = f"Expected an original generated credential in {path.name}."
        raise ValueError(msg)
    return value


def use_os_vault(backup: Path) -> None:
    """Migrate a verified generated set one file at a time, retaining restartability."""
    from lychd.system.desktop.vault import PREFIX, seal_credential

    verify_credential_copy(backup)
    for name in GENERATED:
        path = PATH_POSTGRES_ROOT_DIR / "desktop-credentials" / name.lower()
        if not path.read_bytes().startswith(PREFIX.encode()):
            record = seal_credential(path, recovery_value(path))
            publish_file(path, record, replace=True)
    verify_credential_copy(backup)


def restore_credentials(backup: Path, *, rebind_vault: bool = False) -> None:
    """Verify the whole portable set, then restore missing files or explicitly rebind OS records."""
    from lychd.system.desktop.vault import VaultUnavailableError, matches_recovery, seal_credential

    source = PATH_POSTGRES_ROOT_DIR / "desktop-credentials"
    verify_recovery_directory(backup)
    private_directory(source)
    pending: dict[Path, tuple[bytes, bool]] = {}
    for name in GENERATED:
        target = source / name.lower()
        if os.environ.get(name) or os.environ.get(f"{name}_FILE"):
            msg = f"Remove the external {name} override before recovering generated credentials."
            raise ValueError(msg)
        value = recovery_value(backup / name.lower())
        check_path(target)
        exists = target.exists()
        if exists:
            verify_private_file(target)
            try:
                matches = secrets.compare_digest(generated_value(target, name), value)
            except VaultUnavailableError:
                if not rebind_vault:
                    raise
                matches = matches_recovery(target, target.read_text(encoding="ascii"), value)
            if not matches:
                msg = f"Recovery would replace an existing {name}. Preserved."
                raise ValueError(msg)
            if not rebind_vault:
                continue
        pending[target] = (value, exists)
    if rebind_vault:
        # Seal and verify the whole replacement set before publishing its first file.
        pending = {target: (seal_credential(target, value), exists) for target, (value, exists) in pending.items()}
    for target, (content, exists) in pending.items():
        publish_file(target, content, replace=exists)
    verify_credential_copy(backup)
